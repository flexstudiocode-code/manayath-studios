export interface GalleryImage {
  id: string;
  caption: string;
  alt: string;
  tags: string[];
  aspect: string;
}

export interface Gallery {
  slug: string;
  kind: "culture" | "event";
  title: string;
  subtitle: string;
  description: string;
  cover: string;
  count: number;
  locations?: string[];
  highlights: string[];
  tags: string[];
  images: GalleryImage[];
}

const ASPECTS = ["4/5", "3/4", "1/1", "4/3", "3/4", "16/11"];

function makeImages(
  ids: string[],
  captions: string[],
  tagSets: string[][],
  n: number
): GalleryImage[] {
  const out: GalleryImage[] = [];
  for (let i = 0; i < n; i++) {
    out.push({
      id: ids[i % ids.length],
      caption: captions[i % captions.length],
      alt: `${captions[i % captions.length]} — Kerala wedding photography by Manayath Studios`,
      tags: tagSets[i % tagSets.length],
      aspect: ASPECTS[i % ASPECTS.length],
    });
  }
  return out;
}

